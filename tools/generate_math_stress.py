#!/usr/bin/env python3
"""Generate deterministic f64 reference vectors with mpmath (100 decimal digits).

Only the development-time generator uses mpmath. The checked-in Zig vectors
compile without Python.  Do not mistake this finite corpus for a global ULP
bound or evidence of exact rounding on every platform.
"""
from __future__ import annotations

import argparse
from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "src/math/stress_golden.zig"
MASK = (1 << 64) - 1
SEED = 0x9E3779B97F4A7C15


def splitmix64(state: int) -> tuple[int, int]:
    state = (state + 0x9E3779B97F4A7C15) & MASK
    z = state
    z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & MASK
    z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & MASK
    return (z ^ (z >> 31)) & MASK, state


def hex64(x: float) -> str:
    return f"0x{struct.unpack('>Q', struct.pack('>d', x))[0]:016x}"


def values() -> tuple[list[float], list[tuple[float, float, float]]]:
    anchors = [-1000., -745., -740., -709., -100., -40., -2., -1.,
               -1e-12, -0.0, 0.0, 1e-12, 1., 2., 40., 100., 709., 1000.]
    xs = list(anchors)
    state = SEED
    while len(xs) < 2048:
        z, state = splitmix64(state)
        q = (z >> 11) / float(1 << 53)
        group = len(xs) % 8
        if group == 0:
            x = -745.0 + 1454.0 * q
        elif group == 1:
            x = -40.0 + 80.0 * q
        elif group == 2:
            x = -1e-7 + 2e-7 * q
        elif group == 3:
            x = -1000.0 + 2000.0 * q
        elif group == 4:
            x = -2.0 + 4.0 * q
        elif group == 5:
            x = -720.0 + 20.0 * q
        elif group == 6:
            x = 690.0 + 20.0 * q
        else:
            x = float(int(z % 20001) - 10000) / 32.0
        xs.append(x)
    vectors = []
    for i in range(256):
        a, state = splitmix64(state)
        b, state = splitmix64(state)
        c, state = splitmix64(state)
        base = [-1000.0, -50.0, 0.0, 50.0, 1000.0][i % 5]
        spread = [0.001, 1.0, 10.0, 250.0][(i // 5) % 4]
        u, v, w = ((word >> 11) / float(1 << 53) for word in (a, b, c))
        vectors.append((base + spread * u, base + spread * v, base + spread * w))
    return xs, vectors


def generate() -> str:
    from mpmath import mp
    mp.dps = 100
    xs, vectors = values()
    lines = [
        "//! Generated by tools/generate_math_stress.py with mpmath 100 dps.",
        "//! Fixed SplitMix64 seed; 2048 unary + 256 three-element vectors.",
        "//! DO NOT EDIT; regenerate with --write and verify with --check.",
        "pub const Unary = struct { x_bits: u64, sigmoid_bits: u64, softplus_bits: u64 };",
        "pub const unary = [_]Unary{",
    ]
    for x in xs:
        v = mp.mpf(x)
        sigmoid = 1 / (1 + mp.exp(-v))
        softplus = mp.log1p(mp.exp(v))
        lines.append(
            f"    .{{ .x_bits = {hex64(x)}, .sigmoid_bits = {hex64(float(sigmoid))}, .softplus_bits = {hex64(float(softplus))} }},"
        )
    lines += [
        "};",
        "pub const Vector = struct { inputs: [3]u64, lse_bits: u64, probabilities: [3]u64 };",
        "pub const vectors = [_]Vector{",
    ]
    for vector in vectors:
        vs = [mp.mpf(value) for value in vector]
        maximum = max(vs)
        powers = [mp.exp(value - maximum) for value in vs]
        total = mp.fsum(powers)
        lse = maximum + mp.log(total)
        probabilities = [float(power / total) for power in powers]
        ins = ", ".join(hex64(x) for x in vector)
        outs = ", ".join(hex64(x) for x in probabilities)
        lines.append(
            f"    .{{ .inputs = .{{ {ins} }}, .lse_bits = {hex64(float(lse))}, .probabilities = .{{ {outs} }} }},"
        )
    lines += ["};", ""]
    return "\n".join(lines)


def main() -> None:
    p = argparse.ArgumentParser()
    action = p.add_mutually_exclusive_group(required=True)
    action.add_argument("--write", action="store_true")
    action.add_argument("--check", action="store_true")
    args = p.parse_args()
    try:
        body = generate()
    except ImportError as exc:
        raise SystemExit("Optional test dependency required: python3 -m pip install mpmath") from exc
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != body:
            raise SystemExit("M1.9 high-precision vectors differ; regenerate and review diff")
        print("M1.9 stress references match mpmath (100 dps)")
    else:
        OUTPUT.write_text(body, encoding="utf-8")
        print(f"Wrote {OUTPUT} ({len(body)} bytes)")


if __name__ == "__main__":
    main()
